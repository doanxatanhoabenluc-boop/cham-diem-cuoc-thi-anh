-- Cuộc thi ảnh: chạy toàn bộ file này trong Supabase SQL Editor.
create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  email text not null unique,
  role text not null default 'judge' check (role in ('admin','judge','reporter')),
  created_at timestamptz not null default now()
);

create table if not exists public.entries (
  id uuid primary key default gen_random_uuid(),
  entry_no bigint generated by default as identity unique,
  source_stt bigint,
  author_name text not null,
  unit text not null default '',
  title text not null,
  message text not null default '',
  image_path text not null,
  image_url text not null default '',
  original_filename text,
  created_at timestamptz not null default now()
);

create table if not exists public.scores (
  id uuid primary key default gen_random_uuid(),
  entry_id uuid not null references public.entries(id) on delete cascade,
  judge_id uuid not null references public.profiles(id) on delete cascade,
  content_theme integer not null default 0 check(content_theme between 0 and 30),
  emotion_humanity integer not null default 0 check(emotion_humanity between 0 and 20),
  image_quality integer not null default 0 check(image_quality between 0 and 20),
  creativity integer not null default 0 check(creativity between 0 and 15),
  message integer not null default 0 check(message between 0 and 15),
  comment text not null default '',
  excluded boolean not null default false,
  exclusion_reason text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(entry_id, judge_id)
);

alter table public.entries add column if not exists source_stt bigint;

create index if not exists entries_source_stt_idx on public.entries(source_stt);

create index if not exists scores_entry_id_idx on public.scores(entry_id);
create index if not exists scores_judge_id_idx on public.scores(judge_id);

create or replace function public.current_role()
returns text language sql stable security definer set search_path = public
as $$ select role from public.profiles where id = auth.uid() $$;

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = public
as $$ select coalesce(public.current_role() = 'admin', false) $$;

alter table public.profiles enable row level security;
alter table public.entries enable row level security;
alter table public.scores enable row level security;

drop policy if exists "profiles select self or admin" on public.profiles;
create policy "profiles select self or admin" on public.profiles
for select to authenticated using (id = auth.uid() or public.is_admin());

drop policy if exists "admin update profiles" on public.profiles;
create policy "admin update profiles" on public.profiles
for update to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "authenticated read entries" on public.entries;
create policy "authenticated read entries" on public.entries
for select to authenticated using (true);

drop policy if exists "admin insert entries" on public.entries;
create policy "admin insert entries" on public.entries
for insert to authenticated with check (public.is_admin());

drop policy if exists "admin update entries" on public.entries;
create policy "admin update entries" on public.entries
for update to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "admin delete entries" on public.entries;
create policy "admin delete entries" on public.entries
for delete to authenticated using (public.is_admin());

drop policy if exists "judge read own scores, admin and reporter read all" on public.scores;
create policy "judge read own scores, admin and reporter read all" on public.scores
for select to authenticated using (
  judge_id = auth.uid() or public.current_role() in ('admin','reporter')
);

drop policy if exists "judge insert own scores" on public.scores;
create policy "judge insert own scores" on public.scores
for insert to authenticated with check (
  judge_id = auth.uid() and public.current_role() in ('judge','admin')
);

drop policy if exists "judge update own scores" on public.scores;
create policy "judge update own scores" on public.scores
for update to authenticated using (
  judge_id = auth.uid() and public.current_role() in ('judge','admin')
) with check (
  judge_id = auth.uid() and public.current_role() in ('judge','admin')
);

drop policy if exists "admin delete scores" on public.scores;
create policy "admin delete scores" on public.scores
for delete to authenticated using (public.is_admin());

